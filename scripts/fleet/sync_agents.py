#!/usr/bin/env python3
"""Generate each agent tool's copy of the fleet from the one source in .agents/.

.agents/ is what you edit: agents/<role>/agent.md (the roles), skills/<name>/SKILL.md (the skills)
and hooks.json (agy's hooks). agy reads it as it is. Tools that read AGENTS.md but have no roles
of their own (Codex, Cursor, Copilot, Gemini CLI, ...) read the role and skill files by path, as
AGENTS.md says. This script writes the copies the other tools need:

  Claude Code
    .claude/agents/<role>.md        every subagent role (tools translated; model: inherit, the
                                    session's; effort: the role's thinking level)
    .claude/skills/<name>/          every skill, and the conductor as the `conductor` skill (in
                                    Claude Code the main session conducts: subagents can't start
                                    subagents)
    .claude/settings.json "hooks"   the guards and the stop gate (scripts/fleet/hook.sh); other
                                    keys in that file are left alone

  opencode (cloud or local models)
    .opencode/agent/<role>.md       every subagent role (mode subagent, tools translated, no model:
                                    a subagent runs on the model of the agent that starts it, so a
                                    local model's weights are loaded once)
    .opencode/command/conductor.md  `/conductor`: the main session conducts, on the selected model
    .opencode/plugin/rekkit-guard.js  the shell, paths and read guards (scripts/fleet/hook.sh) before
                                    each tool call, and the Beads context (guard.py prime) in the main
                                    session's system prompt and on compaction; opencode has no hook
                                    that can hold a stop

Usage:
  python3 scripts/fleet/sync_agents.py           # write the copies (make agents)
  python3 scripts/fleet/sync_agents.py --check   # exit 1 if a copy is out of date
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".agents"
CLAUDE = ROOT / ".claude"
OPENCODE = ROOT / ".opencode"
MARK = "Generated by scripts/fleet/sync_agents.py from {src}: edit that file, then run `make agents`."

# agy tool names -> Claude Code's.
CLAUDE_TOOLS = {
    "view_file": ["Read"],
    "read_file": ["Read"],
    "grep_search": ["Grep", "Glob"],
    "find_by_name": ["Glob"],
    "replace_file_content": ["Edit"],
    "edit_file": ["Edit"],
    "write_to_file": ["Write"],
    "write_file": ["Write"],
    "run_command": ["Bash"],
}
EFFORTS = ("low", "medium", "high", "xhigh", "max")


def _hook(check: str, timeout: int) -> dict:
    return {"type": "command", "command": f'"$CLAUDE_PROJECT_DIR"/scripts/fleet/hook.sh {check} claude', "timeout": timeout}


CLAUDE_HOOKS = {
    "SessionStart": [{"hooks": [_hook("prime", 30)]}],
    "PreToolUse": [
        {"matcher": "Bash", "hooks": [_hook("shell", 10)]},
        {"matcher": "Edit|Write|MultiEdit|NotebookEdit", "hooks": [_hook("paths", 10)]},
        {"matcher": "Read|Grep|Glob", "hooks": [_hook("read", 10)]},
        {"matcher": "Agent|Task", "hooks": [_hook("spawn", 10)]},
    ],
    "Stop": [{"hooks": [_hook("gate", 900)]}],
    "SubagentStop": [{"hooks": [_hook("gate", 900)]}],
}


def parse(path: Path) -> tuple[dict, str]:
    """Front matter (flat keys, strings and lists of strings) and body of a Markdown file."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}, text
    head, _, body = text[4:].partition("\n---\n")
    meta: dict = {}
    key = None
    for line in head.splitlines():
        if line.startswith("  - ") and key:
            meta.setdefault(key, []).append(line[4:].strip())
        elif ":" in line:
            key, _, value = line.partition(":")
            key, value = key.strip(), value.strip()
            if value.startswith('"'):
                value = json.loads(value)
            meta[key] = value if value else []
    return meta, body.lstrip("\n")


def front(fields: dict) -> str:
    # JSON strings are valid YAML, so values with ': ' stay one string.
    return "---\n" + "".join(f"{k}: {json.dumps(v) if isinstance(v, str) else v}\n" for k, v in fields.items()) + "---\n"


def note(src: Path) -> str:
    return f"<!-- {MARK.format(src=src.relative_to(ROOT).as_posix())} -->\n\n"


def skill_list(meta: dict, base: str = ".claude/skills") -> str:
    skills = [s.removeprefix("skills/") for s in meta.get("skills", [])]
    if not skills:
        return ""
    # Read by section, not whole: every line read is paid again on every later turn.
    return ("\n# Skills\nYours: " + ", ".join(f"`{base}/{s}/SKILL.md`" for s in skills) + ". Your brief "
            "(`make fleet-task`) has the sections your ticket needs; for another, `make skill-toc SKILL=<name>`, "
            "then `make skill-show SKILL=<name> SECTION=\"<heading>\"`. Do not read a whole SKILL.md.\n")


# agy tool names -> opencode's (every tool not granted is turned off for the role).
OPENCODE_TOOLS = {"view_file": ["read"], "read_file": ["read"], "grep_search": ["grep", "glob"], "find_by_name": ["glob"],
                  "replace_file_content": ["edit"], "edit_file": ["edit"], "write_to_file": ["write"],
                  "write_file": ["write"], "run_command": ["bash"]}
OPENCODE_ALL = ["read", "grep", "glob", "list", "edit", "write", "patch", "bash"]
OPENCODE_PLUGIN = """// Generated by scripts/fleet/sync_agents.py: edit the generator, then run `make agents`.
// The Rekkit guards before each tool call, as agy and Claude Code run them (scripts/fleet/hook.sh):
// no push, sign, release, submodule change, force or recursive delete; nothing under horizon/; no
// code under mods/<id>/content/; no whole decompiled class; no folder sweeps or toolchain reads by a
// role subagent; the subagent token budget. And the Beads context (`bd prime` and, while a mod is in
// progress, its resume page) in the main session's system prompt, as agy and Claude Code get it at
// session start, so no agent runs `bd prime` itself; again when a session is compacted.
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

// Subagents run only under Claude Code, agy and grok. opencode runs a local model (Ollama, LM Studio,
// llama.cpp) most of the time, so opencode's subagent tool is blocked for every model unless the
// operator sets REKKIT_ALLOW_SUBAGENTS=1 in a session on a cloud model. ("task" is the older name.)
const SUBAGENT_TOOLS = new Set(["subagent", "task"]);
const CHECKS = { bash: "shell", edit: "paths", write: "paths", patch: "paths", read: "read", grep: "read", glob: "read", list: "read" };
const HOOK = fileURLToPath(new URL("../../scripts/fleet/hook.sh", import.meta.url));

const guard = (check, payload) =>
  spawnSync("bash", [HOOK, check, "claude"], { input: JSON.stringify(payload ?? {}), encoding: "utf8" });
const prime = () => {
  const r = guard("prime");
  return r.status === 0 ? (r.stdout || "").trim() : "";
};
// One text per session, so the system prompt stays the same from turn to turn (and stays cached).
const primed = new Map();

// opencode (plugin API 1.x) loads a module's default export: an id and a server function returning hooks.
export default {
  id: "rekkit-guard",
  server: async ({ client }) => {
    // A role subagent's session has a parent: it gets no Beads context (its brief is fleet-task's).
    const isSubagent = async (id) => {
      try {
        const r = await client.session.get({ path: { id } });
        return Boolean((r?.data ?? r)?.parentID);
      } catch {
        return false;
      }
    };
    return {
      // Throwing in a before-hook blocks the tool call and returns the message to the model.
      "tool.execute.before": async (input, output) => {
        if (SUBAGENT_TOOLS.has(input.tool) && process.env.REKKIT_ALLOW_SUBAGENTS !== "1")
          throw new Error("Subagents are off on opencode: do the role yourself, one ticket at a time (AGENTS.md).");
        const check = CHECKS[input.tool];
        if (!check) return;
        const r = guard(check, { session_id: input.sessionID ?? "", tool_name: input.tool, tool_input: output?.args ?? {} });
        if (r.status === 2) throw new Error((r.stderr || "Blocked by the Rekkit fleet guard").trim());
      },
      "experimental.chat.system.transform": async (input, output) => {
        const id = input?.sessionID;
        if (!id) return;
        if (!primed.has(id)) primed.set(id, (await isSubagent(id)) ? "" : prime());
        const text = primed.get(id);
        if (text) output.system.push(text);
      },
      "experimental.session.compacting": async (input, output) => {
        if (await isSubagent(input.sessionID)) return;
        const text = prime();
        primed.set(input.sessionID, text);
        if (text) output.context.push(text);
      },
    };
  },
};
"""


def opencode_files() -> dict[Path, str]:
    """Every file the opencode copy consists of, with its content."""
    out: dict[Path, str] = {}
    for src in sorted(SOURCE.glob("agents/*/agent.md")):
        meta, body = parse(src)
        name = meta["name"]
        if meta.get("mainAgent") == "true":
            out[OPENCODE / "command" / "conductor.md"] = front({"description": meta["description"]}) + note(src) + (
                "In opencode you, the main session, are the conductor, on the model opencode has selected. "
                "\"Invoke `x`\" means start the subagent `x` (.opencode/agent/x.md) with the `subagent` tool; it runs on "
                "your model. On opencode NEVER start a subagent (the plugin blocks the subagent tool): do each "
                "role yourself from .agents/agents/<role>/agent.md, one ticket at a time, still writing each "
                "report to the inbox. "
                "Your tools are exactly these, by these names: `bash` (every shell and make command; there is no "
                "`shell`, `shell.execute`, `run_command` or `execute`), `read`, `edit`, `write`, `grep`, `glob`, `list`, "
                "`patch`. If a tool name is rejected, use one of these; do not search for others. "
                "opencode cannot hold your stop: keep going until the mod is finished.\n\n") + body + skill_list(meta, ".agents/skills")
            continue
        granted = {t for tool in meta.get("tools", []) for t in OPENCODE_TOOLS.get(tool, [])}
        tools = "".join(f"\n  {t}: {'true' if t in granted else 'false'}" for t in OPENCODE_ALL)
        head = front({"description": meta["description"], "mode": "subagent"})
        head = head[:-4] + f"tools:{tools}\n---\n"
        out[OPENCODE / "agent" / f"{name}.md"] = head + note(src) + body + skill_list(meta, ".agents/skills")
    out[OPENCODE / "plugin" / "rekkit-guard.js"] = OPENCODE_PLUGIN
    return out


def claude_files() -> dict[Path, str]:
    """Every file the Claude Code copy consists of, with its content."""
    out: dict[Path, str] = {}
    for src in sorted(SOURCE.glob("agents/*/agent.md")):
        meta, body = parse(src)
        name = meta["name"]
        if meta.get("mainAgent") == "true":
            out[CLAUDE / "skills" / name / "SKILL.md"] = front({
                "name": name, "description": meta["description"],
            }) + note(src) + (
                "In Claude Code you, the main session, are the conductor. \"Invoke `x`\" means start the "
                "subagent `x` (.claude/agents/x.md) with the Agent tool; several at once for the parallel "
                "steps. \"Message\" an agent: continue that same subagent rather than starting a new one.\n\n"
            ) + body + skill_list(meta)
            continue
        tools = [t for tool in meta.get("tools", []) for t in CLAUDE_TOOLS.get(tool, [])]
        fields = {"name": name, "description": meta["description"]}
        if tools:
            fields["tools"] = ", ".join(dict.fromkeys(tools))
        # Every role runs on the session's model (the person picked it); only its thinking level differs.
        fields["model"] = "inherit"
        if meta.get("effort") in EFFORTS:
            fields["effort"] = meta["effort"]
        out[CLAUDE / "agents" / f"{name}.md"] = front(fields) + note(src) + body + skill_list(meta)
    for skill_dir in sorted(p for p in SOURCE.glob("skills/*") if p.is_dir()):
        for src in sorted(p for p in skill_dir.rglob("*") if p.is_file()):
            dest = CLAUDE / "skills" / skill_dir.name / src.relative_to(skill_dir)
            text = src.read_text(encoding="utf-8")
            if src.name == "SKILL.md":
                meta, body = parse(src)
                text = front({k: v for k, v in meta.items() if isinstance(v, str)}) + note(src) + body
            out[dest] = text
    settings_path = CLAUDE / "settings.json"
    settings = json.loads(settings_path.read_text(encoding="utf-8")) if settings_path.is_file() else {}
    settings["hooks"] = CLAUDE_HOOKS
    out[settings_path] = json.dumps(settings, indent=2) + "\n"
    return out


def generated(path: Path) -> bool:
    try:
        return "Generated by scripts/fleet/sync_agents.py" in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def stale(wanted: dict[Path, str]) -> list[Path]:
    """Generated files (or skill folders) whose source is gone."""
    old = [p for p in [*(CLAUDE / "agents").glob("*.md"), *(OPENCODE / "agent").glob("*.md"),
                       *(OPENCODE / "command").glob("*.md")] if p not in wanted and generated(p)]
    for skill in (CLAUDE / "skills").glob("*/SKILL.md"):
        if skill not in wanted and generated(skill):
            old.append(skill.parent)
    return old


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Report out-of-date copies; change nothing")
    args = parser.parse_args()

    wanted = {**claude_files(), **opencode_files()}
    changed = [p for p, text in wanted.items()
               if not p.is_file() or p.read_text(encoding="utf-8") != text]
    old = stale(wanted)
    for p in changed + old:
        print(f"{'out of date' if args.check else 'wrote' if p in wanted else 'removed'}: "
              f"{p.relative_to(ROOT).as_posix()}")
    if args.check:
        if changed or old:
            print("Run `make agents` (python3 scripts/fleet/sync_agents.py) to regenerate.", file=sys.stderr)
            return 1
        print(f"Agent copies up to date ({len(wanted)} files).")
        return 0
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p], encoding="utf-8", newline="\n")
    for p in old:
        shutil.rmtree(p) if p.is_dir() else p.unlink()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
